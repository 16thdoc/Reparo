function Convert-DeploymentToggle {
    param(
        [string]$Value,
        [bool]$Default,
        [string]$Name
    )

    # NinjaOne can pass the literal type name "System.String" for an omitted
    # imported-script field. Treat it as omitted instead of failing parameter binding.
    $normalized = if ($null -eq $Value) { '' } else { $Value.Trim().ToLowerInvariant() }
    if ([string]::IsNullOrWhiteSpace($normalized) -or $normalized -eq 'system.string') {
        return $Default
    }

    if ($normalized -in @('true', '$true', '1', 'yes', 'on')) { return $true }
    if ($normalized -in @('false', '$false', '0', 'no', 'off')) { return $false }
    throw "$Name must be true or false; received '$Value'."
}

function Resolve-DeploymentString {
    param(
        [string]$Value,
        [string]$Default
    )

    if ([string]::IsNullOrWhiteSpace($Value) -or $Value.Trim() -eq 'System.String') {
        return $Default
    }

    return $Value
}

function Get-DeploymentSha256 {
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    # Get-FileHash is absent from some old Windows PowerShell hosts still found in
    # RMM execution contexts. Use the .NET primitive directly so payload integrity
    # verification works everywhere Reparo supports.
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    $stream = [System.IO.File]::OpenRead($Path)
    try {
        return ([System.BitConverter]::ToString($sha256.ComputeHash($stream))).Replace('-', '')
    }
    finally {
        $stream.Dispose()
        $sha256.Dispose()
    }
}

